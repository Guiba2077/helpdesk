CREATE OR REPLACE VIEW app.vw_chamados_detalhados AS
SELECT c.id,
       c.protocolo,
       c.titulo,
       c.descricao,
       c.categoria,
       c.prioridade,
       c.status,
       c.ativo,
       c.solicitante_id,
       s.nome   AS solicitante_nome,
       s.email  AS solicitante_email,
       s.setor  AS solicitante_setor,
       c.tecnico_id,
       ut.nome  AS tecnico_nome,
       t.especialidade     AS tecnico_especialidade,
       t.nivel_atendimento AS tecnico_nivel,
       c.solucao,
       c.aberto_em,
       c.atendimento_em,
       c.fechado_em,
       c.atualizado_em,
       round(EXTRACT(EPOCH FROM (COALESCE(c.fechado_em, now()) - c.aberto_em)) / 3600, 2) AS horas_em_aberto,
       (SELECT count(*) FROM app.apontamento_chamado a WHERE a.chamado_id = c.id) AS total_apontamentos
  FROM app.chamado c
  JOIN app.usuario s  ON s.id = c.solicitante_id
  LEFT JOIN app.tecnico t ON t.id = c.tecnico_id
  LEFT JOIN app.usuario ut ON ut.id = t.usuario_id;

CREATE OR REPLACE VIEW audit.vw_auditoria_prioridade AS
SELECT a.id,
       a.chamado_id,
       a.protocolo_chamado,
       c.titulo AS titulo_chamado,
       a.prioridade_anterior,
       a.prioridade_nova,
       a.alterado_por,
       u.nome   AS alterado_por_nome,
       a.justificativa,
       a.alterado_em
  FROM audit.auditoria_prioridade a
  LEFT JOIN app.chamado c ON c.id = a.chamado_id
  LEFT JOIN app.usuario u ON u.id = a.alterado_por;

