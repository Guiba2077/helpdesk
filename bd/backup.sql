GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app TO rl_escritor;
GRANT SELECT ON ALL TABLES IN SCHEMA app   TO rl_leitor;
GRANT SELECT ON ALL TABLES IN SCHEMA audit TO rl_escritor, rl_leitor;

REVOKE EXECUTE ON ALL ROUTINES IN SCHEMA app FROM PUBLIC;
GRANT EXECUTE ON ALL ROUTINES IN SCHEMA app TO rl_escritor;
GRANT EXECUTE ON FUNCTION app.fn_metricas_sla_tecnico() TO rl_leitor;
GRANT EXECUTE ON FUNCTION app.fn_usuario_sessao() TO rl_leitor;

ALTER DEFAULT PRIVILEGES IN SCHEMA app   GRANT SELECT, INSERT, UPDATE ON TABLES TO rl_escritor;
ALTER DEFAULT PRIVILEGES IN SCHEMA app   GRANT USAGE, SELECT ON SEQUENCES TO rl_escritor;
ALTER DEFAULT PRIVILEGES IN SCHEMA app   GRANT SELECT ON TABLES TO rl_leitor;
ALTER DEFAULT PRIVILEGES IN SCHEMA audit GRANT SELECT ON TABLES TO rl_escritor, rl_leitor;

