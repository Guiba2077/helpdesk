-- =============================================================================
-- Helpdesk TI (Tema G3) - Script de carga inicial do PostgreSQL 16
--
-- Executado automaticamente pelo container "db" na primeira inicializacao
-- (pasta /docker-entrypoint-initdb.d), ja conectado ao banco "helpdesk" criado
-- pela variavel POSTGRES_DB. Para rodar manualmente em outro servidor:
--     psql -U postgres -d helpdesk -f bd/backup.sql
--
-- Conteudo:
--   1. Schemas e extensoes (app, audit, ext)
--   2. Roles (rl_leitor, rl_escritor), contas de aplicacao, timeouts e search_path
--   3. Tabelas (DDL)
--   4. Functions e triggers: protocolo, transicao de status, historico, auditoria
--   5. Procedure sp_alocar_chamado
--   6. Function fn_metricas_sla_tecnico
--   7. Views
--   8. Privilegios (GRANT / REVOKE)
--   9. Seeds (DML) para a primeira execucao
-- =============================================================================

\set ON_ERROR_STOP on

-- =============================================================================
-- 1. SCHEMAS E EXTENSOES
-- =============================================================================
CREATE SCHEMA IF NOT EXISTS app;
CREATE SCHEMA IF NOT EXISTS audit;
CREATE SCHEMA IF NOT EXISTS ext;

COMMENT ON SCHEMA app   IS 'Dominio operacional: usuarios, tecnicos, chamados, historico e apontamentos';
COMMENT ON SCHEMA audit IS 'Trilha de auditoria imutavel (alteracoes de prioridade)';
COMMENT ON SCHEMA ext   IS 'Extensoes: pgcrypto e pg_stat_statements';

CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA ext;
CREATE EXTENSION IF NOT EXISTS pg_stat_statements WITH SCHEMA ext;

-- =============================================================================
-- 2. ROLES, CONTAS DE APLICACAO, TIMEOUTS E SEARCH_PATH
--    rl_escritor: pool principal do backend (operacoes transacionais)
--    rl_leitor:   pool de relatorios e auditoria (somente leitura, timeout curto)
-- =============================================================================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rl_leitor') THEN
        CREATE ROLE rl_leitor NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rl_escritor') THEN
        CREATE ROLE rl_escritor NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'usr_helpdesk_escritor') THEN
        CREATE ROLE usr_helpdesk_escritor LOGIN PASSWORD 'escritor123'
            IN ROLE rl_escritor CONNECTION LIMIT 20;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'usr_helpdesk_leitor') THEN
        CREATE ROLE usr_helpdesk_leitor LOGIN PASSWORD 'leitor123'
            IN ROLE rl_leitor CONNECTION LIMIT 15;
    END IF;
END
$$;

-- Timeout curto para relatorios: qualquer consulta da conta de leitura acima de
-- 3 segundos e cancelada pelo servidor (SQLSTATE 57014). O backend converte em HTTP 504.
ALTER ROLE usr_helpdesk_leitor SET statement_timeout = '3s';
ALTER ROLE usr_helpdesk_leitor SET default_transaction_read_only = on;

-- O pgcrypto fica no schema ext; o search_path garante que crypt() e gen_salt()
-- sejam encontrados sem qualificar o nome.
ALTER DATABASE :"DBNAME" SET search_path = app, ext;
ALTER ROLE usr_helpdesk_escritor SET search_path = app, ext;
ALTER ROLE usr_helpdesk_leitor SET search_path = app, audit, ext;

-- Hardening: nenhum objeto da aplicacao vive em public e so as roles da
-- aplicacao podem se conectar ao banco.
REVOKE ALL ON SCHEMA public FROM PUBLIC;
REVOKE ALL ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO rl_leitor, rl_escritor;

