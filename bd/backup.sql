-- 5. PROCEDURE: alocacao de tecnico (ABERTO -> ATENDIMENTO)
--    Chamada pelo backend: CALL app.sp_alocar_chamado(chamado, tecnico, usuario)
-- =============================================================================
CREATE OR REPLACE PROCEDURE app.sp_alocar_chamado(
    p_chamado_id BIGINT,
    p_tecnico_id BIGINT,
    p_usuario_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_status     TEXT;
    v_protocolo  TEXT;
    v_disponivel BOOLEAN;
    v_ativo      BOOLEAN;
BEGIN
    SELECT status, protocolo
      INTO v_status, v_protocolo
      FROM app.chamado
     WHERE id = p_chamado_id AND ativo
       FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Chamado % nao encontrado ou inativo', p_chamado_id USING ERRCODE = 'P0002';
    END IF;
    IF v_status <> 'ABERTO' THEN
        RAISE EXCEPTION 'Somente chamados ABERTOS podem receber tecnico (chamado % esta em %)', v_protocolo, v_status
            USING ERRCODE = 'P0001';
    END IF;

    SELECT disponivel, ativo
      INTO v_disponivel, v_ativo
      FROM app.tecnico
     WHERE id = p_tecnico_id;

    IF NOT FOUND OR NOT v_ativo THEN
        RAISE EXCEPTION 'Tecnico % nao encontrado ou inativo', p_tecnico_id USING ERRCODE = 'P0002';
    END IF;
    IF NOT v_disponivel THEN
        RAISE EXCEPTION 'Tecnico % esta indisponivel no momento', p_tecnico_id USING ERRCODE = 'P0001';
    END IF;

    -- Garante o autor para a trigger de historico mesmo se a aplicacao nao definiu
    PERFORM set_config('app.current_user_id', p_usuario_id::TEXT, true);

    UPDATE app.chamado
       SET tecnico_id     = p_tecnico_id,
           status         = 'ATENDIMENTO',
           atendimento_em = now(),
           atualizado_em  = now()
     WHERE id = p_chamado_id;
END
$$;

-- =============================================================================
-- 6. FUNCTION: metricas de SLA por tecnico (relatorio)
--    Consumida pelo backend: SELECT * FROM app.fn_metricas_sla_tecnico()
-- =============================================================================
CREATE OR REPLACE FUNCTION app.fn_metricas_sla_tecnico()
RETURNS TABLE (
    tecnico_id           BIGINT,
    tecnico_nome         VARCHAR,
    especialidade        VARCHAR,
    total_atribuidos     BIGINT,
    total_fechados       BIGINT,
    total_em_atendimento BIGINT,
    tempo_medio_horas    NUMERIC
)
LANGUAGE sql
STABLE
AS $$
    SELECT t.id,
           u.nome,
           t.especialidade,
           count(c.id),
           count(c.id) FILTER (WHERE c.status = 'FECHADO'),
           count(c.id) FILTER (WHERE c.status = 'ATENDIMENTO'),
           round(avg(EXTRACT(EPOCH FROM (c.fechado_em - c.aberto_em)) / 3600)
                 FILTER (WHERE c.status = 'FECHADO'), 2)
      FROM app.tecnico t
      JOIN app.usuario u ON u.id = t.usuario_id
      LEFT JOIN app.chamado c ON c.tecnico_id = t.id AND c.ativo
     WHERE t.ativo
     GROUP BY t.id, u.nome, t.especialidade
     ORDER BY count(c.id) FILTER (WHERE c.status = 'FECHADO') DESC, u.nome
$$;

