-- Usuario da sessao: o backend executa set_config('app.current_user_id', id, true)
-- dentro de cada transacao, antes de gravar. As triggers leem daqui.
CREATE OR REPLACE FUNCTION app.fn_usuario_sessao()
RETURNS BIGINT
LANGUAGE sql
STABLE
AS $$
    SELECT NULLIF(current_setting('app.current_user_id', true), '')::BIGINT
$$;

-- 4.1 Protocolo sequencial por ano: CHM-2026-0001
CREATE OR REPLACE FUNCTION app.fn_gerar_protocolo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.protocolo IS NULL OR NEW.protocolo = '' THEN
        NEW.protocolo := 'CHM-' || to_char(now(), 'YYYY') || '-'
                      || lpad(nextval('app.seq_protocolo_chamado')::TEXT, 4, '0');
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_gerar_protocolo
    BEFORE INSERT ON app.chamado
    FOR EACH ROW
    EXECUTE FUNCTION app.fn_gerar_protocolo();

-- 4.2 Regras de transicao: ABERTO -> ATENDIMENTO -> FECHADO
CREATE OR REPLACE FUNCTION app.fn_validar_transicao_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = NEW.status THEN
        RETURN NEW;
    END IF;

    IF OLD.status = 'FECHADO' THEN
        RAISE EXCEPTION 'Chamado % ja esta FECHADO e nao pode mudar de status', OLD.protocolo
            USING ERRCODE = 'P0001';
    END IF;
    IF OLD.status = 'ABERTO' AND NEW.status <> 'ATENDIMENTO' THEN
        RAISE EXCEPTION 'Transicao invalida: um chamado ABERTO so pode ir para ATENDIMENTO'
            USING ERRCODE = 'P0001';
    END IF;
    IF OLD.status = 'ATENDIMENTO' AND NEW.status <> 'FECHADO' THEN
        RAISE EXCEPTION 'Transicao invalida: um chamado em ATENDIMENTO so pode ir para FECHADO'
            USING ERRCODE = 'P0001';
    END IF;
    IF NEW.status = 'ATENDIMENTO' AND NEW.tecnico_id IS NULL THEN
        RAISE EXCEPTION 'Nao e possivel iniciar o atendimento sem um tecnico alocado'
            USING ERRCODE = 'P0001';
    END IF;
    IF NEW.status = 'FECHADO' AND (NEW.solucao IS NULL OR btrim(NEW.solucao) = '') THEN
        RAISE EXCEPTION 'Nao e possivel encerrar o chamado sem registrar a solucao'
            USING ERRCODE = 'P0001';
    END IF;

    IF NEW.status = 'ATENDIMENTO' AND NEW.atendimento_em IS NULL THEN
        NEW.atendimento_em := now();
    END IF;
    IF NEW.status = 'FECHADO' AND NEW.fechado_em IS NULL THEN
        NEW.fechado_em := now();
    END IF;
    NEW.atualizado_em := now();
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_validar_transicao_status
    BEFORE UPDATE OF status ON app.chamado
    FOR EACH ROW
    EXECUTE FUNCTION app.fn_validar_transicao_status();

-- 4.3 Historico de status (exigencia do G3): grava cada mudanca com o autor
CREATE OR REPLACE FUNCTION app.fn_registrar_historico_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_observacao TEXT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO app.historico_chamado (chamado_id, status_anterior, status_novo, alterado_por, observacao)
        VALUES (NEW.id, NULL, NEW.status,
                COALESCE(app.fn_usuario_sessao(), NEW.solicitante_id),
                'Chamado aberto');
        RETURN NEW;
    END IF;

    IF OLD.status IS DISTINCT FROM NEW.status THEN
        v_observacao := CASE NEW.status
            WHEN 'ATENDIMENTO' THEN 'Tecnico alocado e atendimento iniciado'
            WHEN 'FECHADO'     THEN 'Chamado encerrado com solucao registrada'
            ELSE 'Status alterado'
        END;
        INSERT INTO app.historico_chamado (chamado_id, status_anterior, status_novo, alterado_por, observacao)
        VALUES (NEW.id, OLD.status, NEW.status, app.fn_usuario_sessao(), v_observacao);
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_historico_status
    AFTER INSERT OR UPDATE OF status ON app.chamado
    FOR EACH ROW
    EXECUTE FUNCTION app.fn_registrar_historico_status();

-- 4.4 Auditoria de prioridade (exigencia do G3)
--     SECURITY DEFINER: roda com os privilegios do dono (postgres). Assim a conta
--     da aplicacao consegue gerar auditoria sem ter INSERT direto no schema audit.
CREATE OR REPLACE FUNCTION audit.fn_auditar_prioridade()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = app, audit, pg_temp
AS $$
BEGIN
    IF OLD.prioridade IS DISTINCT FROM NEW.prioridade THEN
        INSERT INTO audit.auditoria_prioridade
            (chamado_id, protocolo_chamado, prioridade_anterior, prioridade_nova, alterado_por, justificativa)
        VALUES
            (NEW.id, NEW.protocolo, OLD.prioridade, NEW.prioridade,
             app.fn_usuario_sessao(),
             NULLIF(current_setting('app.motivo_prioridade', true), ''));
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_auditoria_prioridade
    AFTER UPDATE OF prioridade ON app.chamado
    FOR EACH ROW
    EXECUTE FUNCTION audit.fn_auditar_prioridade();

-- 4.5 Auditoria imutavel: nem UPDATE nem DELETE, para nenhum usuario
CREATE OR REPLACE FUNCTION audit.fn_bloquear_alteracao()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Registros de auditoria sao imutaveis (operacao % bloqueada)', TG_OP
        USING ERRCODE = 'P0001';
END
$$;

CREATE TRIGGER trg_auditoria_imutavel
    BEFORE UPDATE OR DELETE ON audit.auditoria_prioridade
    FOR EACH ROW
    EXECUTE FUNCTION audit.fn_bloquear_alteracao();

